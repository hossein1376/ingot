//! The structural form (05-tooling section 35) and the `main` error line
//! (section 33.1).
//!
//! The compiler generates one IR function per printed type instance,
//! `_I.show.N(ptr)`, that writes the value the pointer addresses to standard
//! error. The pieces of text go through `std.sys.rt`'s `write_bytes`, the integers
//! through `print_i64` and `print_u64`, and a `[]u8` through `print_str`: the
//! runtime stays ordinary Ingot code and the compiler only calls it by path.
//!
//! Every type but floats is covered (decisions.md, 2026-11-19): a float, a
//! pointer, a reference, a `&dyn`, a closure or a function value is a build-time
//! `not implemented` entry naming R5 (`std.fmt`).

use super::*;

/// The printer functions generated so far.
#[derive(Default)]
pub(crate) struct ShowState {
    /// The symbol of the printer of each type.
    symbols: BTreeMap<TypeId, String>,
    /// Types whose printer is named but not yet generated.
    pending: Vec<TypeId>,
}

/// A function body being written: its lines and the counters for fresh names.
struct Fb {
    lines: Vec<String>,
    tmp: usize,
    label: usize,
}

impl Fb {
    fn new() -> Fb {
        Fb {
            lines: Vec::new(),
            tmp: 0,
            label: 0,
        }
    }

    fn line(&mut self, text: impl Into<String>) {
        self.lines.push(format!("  {}", text.into()));
    }

    fn tmp(&mut self) -> String {
        let n = self.tmp;
        self.tmp += 1;
        format!("%s{n}")
    }

    fn label(&mut self, prefix: &str) -> String {
        let n = self.label;
        self.label += 1;
        format!("{prefix}{n}")
    }

    fn start(&mut self, label: &str) {
        self.lines.push(format!("{label}:"));
    }

    /// `base + offset` bytes, as a pointer.
    fn at(&mut self, base: &str, offset: u64) -> String {
        if offset == 0 {
            return base.to_string();
        }
        let out = self.tmp();
        self.line(format!(
            "{out} = getelementptr i8, ptr {base}, i64 {offset}"
        ));
        out
    }
}

/// An enum tag as an LLVM integer constant.
fn tag_literal(value: i128) -> String {
    value.to_string()
}

impl<'p> Codegen<'p> {
    /// The symbol of a `std.sys.rt` function the printers call. It is a root of the
    /// executable when `main` is fallible (`collect_instances`).
    fn show_rt(&self, name: &str) -> Result<String, BuildError> {
        let def = find_module_item(self.program.sema, "std.sys.rt", name)
            .ok_or_else(|| BuildError::Internal(format!("std.sys.rt.{name} is missing")))?;
        let key = InstanceKey {
            owner: def,
            body: InstanceBody::Item,
            subst: Subst::new(),
        };
        self.symbols
            .get(&key)
            .cloned()
            .map(|s| global_ref(&s))
            .ok_or_else(|| BuildError::Internal(format!("std.sys.rt.{name} was not rooted")))
    }

    /// Write fixed text to standard error.
    fn show_text(&mut self, fb: &mut Fb, text: &str) -> Result<(), BuildError> {
        let write = self.show_rt("write_bytes")?;
        let global = self.add_string(text.as_bytes());
        fb.line(format!(
            "call void {write}(ptr @{global}, i64 {})",
            text.len()
        ));
        Ok(())
    }

    /// The symbol of the printer of `ty`; the function is generated by
    /// `generate_printers`.
    fn show_symbol(&mut self, ty: TypeId) -> String {
        if let Some(symbol) = self.show.symbols.get(&ty) {
            return symbol.clone();
        }
        let symbol = format!("_I.show.{}", self.show.symbols.len());
        self.show.symbols.insert(ty, symbol.clone());
        self.show.pending.push(ty);
        symbol
    }

    /// Print the value of type `ty` at `ptr`: inline for the scalars, a call to the
    /// type's printer for everything else.
    fn show_value(&mut self, fb: &mut Fb, ptr: &str, ty: TypeId) -> Result<(), BuildError> {
        match self.program.decls.types.kind(ty).clone() {
            TyKind::Int(i) => {
                let bits = i.bits();
                let ll = format!("i{bits}");
                let loaded = fb.tmp();
                fb.line(format!("{loaded} = load {ll}, ptr {ptr}"));
                let wide = if bits == 64 {
                    loaded
                } else {
                    let out = fb.tmp();
                    let op = if i.signed() { "sext" } else { "zext" };
                    fb.line(format!("{out} = {op} {ll} {loaded} to i64"));
                    out
                };
                let callee = self.show_rt(if i.signed() { "print_i64" } else { "print_u64" })?;
                fb.line(format!("call void {callee}(i64 {wide})"));
                Ok(())
            }
            TyKind::Bool => {
                let byte = fb.tmp();
                fb.line(format!("{byte} = load i8, ptr {ptr}"));
                let truth = fb.tmp();
                fb.line(format!("{truth} = icmp ne i8 {byte}, 0"));
                let yes = self.add_string(b"true");
                let no = self.add_string(b"false");
                let at = fb.tmp();
                fb.line(format!("{at} = select i1 {truth}, ptr @{yes}, ptr @{no}"));
                let len = fb.tmp();
                fb.line(format!("{len} = select i1 {truth}, i64 4, i64 5"));
                let write = self.show_rt("write_bytes")?;
                fb.line(format!("call void {write}(ptr {at}, i64 {len})"));
                Ok(())
            }
            TyKind::Slice(_, elem) if self.is_u8(elem) => {
                let (data, len) = self.show_slice_parts(fb, ptr);
                let callee = self.show_rt("print_str")?;
                fb.line(format!("call void {callee}(ptr {data}, i64 {len})"));
                Ok(())
            }
            TyKind::Adt(def, _) if Some(def) == self.program.decls.builtins.idx => {
                self.ni("the structural form of `Idx` (R5, std.fmt)")
            }
            TyKind::Adt(..)
            | TyKind::Tuple(_)
            | TyKind::Array(..)
            | TyKind::Slice(..)
            | TyKind::Optional(_) => {
                self.type_info(ty)?;
                let symbol = global_ref(&self.show_symbol(ty));
                fb.line(format!("call void {symbol}(ptr {ptr})"));
                Ok(())
            }
            TyKind::Float(_) => self.ni("the structural form of a float (R5, std.fmt)"),
            TyKind::RawPtr(..) | TyKind::Ref(..) => {
                self.ni("the structural form of a pointer or reference (R5, std.fmt)")
            }
            TyKind::Dyn(..) | TyKind::DynFn(..) => {
                self.ni("the structural form of a `&dyn` (R5, std.fmt)")
            }
            TyKind::FnPtr(_) | TyKind::Closure(..) => {
                self.ni("the structural form of a function value or closure (R5, std.fmt)")
            }
            TyKind::Void | TyKind::Never => self.ni("the structural form of `void` (R5, std.fmt)"),
            TyKind::Result(..) => self.ni("the structural form of a `T ! E` value (R5, std.fmt)"),
            TyKind::Vector(..) | TyKind::Mask(_) => {
                self.ni("the structural form of a vector (R5, std.fmt)")
            }
            TyKind::Param(_) | TyKind::Projection(..) | TyKind::Poison => {
                self.ni("the structural form of a type with no concrete form (R5, std.fmt)")
            }
        }
    }

    fn is_u8(&self, ty: TypeId) -> bool {
        matches!(self.program.decls.types.kind(ty), TyKind::Int(IntTy::U8))
    }

    /// The data pointer and length of the slice at `ptr`.
    fn show_slice_parts(&mut self, fb: &mut Fb, ptr: &str) -> (String, String) {
        let data = fb.tmp();
        fb.line(format!("{data} = load ptr, ptr {ptr}"));
        let len_at = fb.at(ptr, 8);
        let len = fb.tmp();
        fb.line(format!("{len} = load i64, ptr {len_at}"));
        (data, len)
    }

    /// Generate every printer named so far, and the ones their elements name.
    pub(crate) fn generate_printers(&mut self, from: ModuleId) -> Result<(), BuildError> {
        while let Some(ty) = self.show.pending.pop() {
            let symbol = self.show.symbols[&ty].clone();
            let mut fb = Fb::new();
            self.show_type(&mut fb, ty, from)?;
            let mut out = String::new();
            out.push_str(&format!(
                "define internal void {}(ptr %v) nounwind #0 {{\n",
                global_ref(&symbol)
            ));
            out.push_str("entry:\n");
            for line in &fb.lines {
                out.push_str(line);
                out.push('\n');
            }
            out.push_str("  ret void\n}\n");
            self.functions.push(out);
        }
        Ok(())
    }

    /// The body of the printer of an aggregate, slice or optional: it starts in
    /// `entry` and ends in a block that falls through to `ret void`.
    fn show_type(&mut self, fb: &mut Fb, ty: TypeId, from: ModuleId) -> Result<(), BuildError> {
        match self.program.decls.types.kind(ty).clone() {
            TyKind::Adt(def, args) => match self.program.decls.item(def).cloned() {
                Some(ItemSig::Struct(sig)) => self.show_struct(fb, ty, def, &args, &sig, from),
                Some(ItemSig::Enum(sig)) => {
                    let name = self.type_display(ty);
                    let names: Vec<String> = sig.variants.iter().map(|v| v.name.clone()).collect();
                    self.show_enum(fb, ty, &format!("{name}."), &names)
                }
                _ => self.ni("the structural form of a built-in type with no declaration"),
            },
            TyKind::Optional(_) => {
                self.show_enum(fb, ty, ".", &["none".to_string(), "some".to_string()])
            }
            TyKind::Tuple(elems) => {
                let layout = self.layout(ty)?;
                self.show_text(fb, "(")?;
                for (i, elem) in elems.iter().enumerate() {
                    if i > 0 {
                        self.show_text(fb, ", ")?;
                    }
                    let offset = layout.fields.get(i).map(|f| f.offset).ok_or_else(|| {
                        BuildError::Internal(format!("no layout entry for tuple field {i}"))
                    })?;
                    let at = fb.at("%v", offset);
                    self.show_value(fb, &at, *elem)?;
                }
                self.show_text(fb, ")")
            }
            TyKind::Array(elem, _) => {
                self.type_info(ty)?;
                let Shape::Array { len, .. } = self.types[&ty].shape.clone() else {
                    return Err(BuildError::Internal("an array with no shape".to_string()));
                };
                self.show_elements(fb, elem, &format!("{len}"), "%v")
            }
            TyKind::Slice(_, elem) => {
                let (data, len) = self.show_slice_parts(fb, "%v");
                self.show_elements(fb, elem, &len, &data)
            }
            _ => Err(BuildError::Internal(
                "a printer requested for a scalar".to_string(),
            )),
        }
    }

    /// `[a, b]` for `len` elements of `elem` starting at `data`. Starts in `entry`.
    fn show_elements(
        &mut self,
        fb: &mut Fb,
        elem: TypeId,
        len: &str,
        data: &str,
    ) -> Result<(), BuildError> {
        let stride = self.layout(elem)?.size;
        self.show_text(fb, "[")?;
        let head = fb.label("head");
        let body = fb.label("body");
        let sep = fb.label("sep");
        let item = fb.label("item");
        let end = fb.label("end");
        let index = fb.tmp();
        let next = fb.tmp();
        fb.line(format!("br label %{head}"));
        fb.start(&head);
        fb.line(format!(
            "{index} = phi i64 [ 0, %entry ], [ {next}, %{item} ]"
        ));
        let more = fb.tmp();
        fb.line(format!("{more} = icmp ult i64 {index}, {len}"));
        fb.line(format!("br i1 {more}, label %{body}, label %{end}"));
        fb.start(&body);
        let later = fb.tmp();
        fb.line(format!("{later} = icmp ne i64 {index}, 0"));
        fb.line(format!("br i1 {later}, label %{sep}, label %{item}"));
        fb.start(&sep);
        self.show_text(fb, ", ")?;
        fb.line(format!("br label %{item}"));
        fb.start(&item);
        let offset = fb.tmp();
        fb.line(format!("{offset} = mul i64 {index}, {stride}"));
        let at = fb.tmp();
        fb.line(format!("{at} = getelementptr i8, ptr {data}, i64 {offset}"));
        self.show_value(fb, &at, elem)?;
        fb.line(format!("{next} = add i64 {index}, 1"));
        fb.line(format!("br label %{head}"));
        fb.start(&end);
        self.show_text(fb, "]")
    }

    /// `Name.{ a: 1, b: 2 }`: the fields visible from `from`, then `..` when some
    /// are not (05 section 35).
    fn show_struct(
        &mut self,
        fb: &mut Fb,
        ty: TypeId,
        def: DefId,
        args: &[GenericArg],
        sig: &ingot_sema::sigs::StructSig,
        from: ModuleId,
    ) -> Result<(), BuildError> {
        let name = self.type_display(ty);
        let layout = self.layout(ty)?;
        let subst = self.program.decls.subst_for(def, args);
        let declared = self.program.sema.def(def).module;
        let mut visible = Vec::new();
        let mut hidden = false;
        for (i, f) in sig.fields.iter().enumerate() {
            if self
                .program
                .sema
                .field_visible(declared, from, f.public, f.pkg)
            {
                let offset = layout.fields.get(i).map(|l| l.offset).ok_or_else(|| {
                    BuildError::Internal(format!("no layout entry for the field `{}`", f.name))
                })?;
                let fty = self.program.decls.instantiate(f.ty, &subst);
                visible.push((f.name.clone(), offset, fty));
            } else {
                hidden = true;
            }
        }
        if visible.is_empty() && !hidden {
            return self.show_text(fb, &format!("{name}.{{}}"));
        }
        self.show_text(fb, &format!("{name}.{{ "))?;
        for (i, (field, offset, fty)) in visible.iter().enumerate() {
            if i > 0 {
                self.show_text(fb, ", ")?;
            }
            self.show_text(fb, &format!("{field}: "))?;
            let at = fb.at("%v", *offset);
            self.show_value(fb, &at, *fty)?;
        }
        if hidden {
            self.show_text(fb, if visible.is_empty() { ".." } else { ", .." })?;
        }
        self.show_text(fb, " }")
    }

    /// `Name.variant` or `Name.variant(payload)`, and `.none` / `.some(x)` for
    /// `?T` (`prefix` is `Name.` or `.`).
    fn show_enum(
        &mut self,
        fb: &mut Fb,
        ty: TypeId,
        prefix: &str,
        names: &[String],
    ) -> Result<(), BuildError> {
        self.type_info(ty)?;
        let Shape::Enum {
            tag,
            payload_offset,
            variants,
            niche,
        } = self.types[&ty].shape.clone()
        else {
            return Err(BuildError::Internal("an enum with no shape".to_string()));
        };
        let done = fb.label("done");
        let labels: Vec<String> = variants.iter().map(|_| fb.label("variant")).collect();
        if niche {
            // `?&T`, `?[]T` and `?fn`: the first word is null for `.none`.
            let word = fb.tmp();
            fb.line(format!("{word} = load ptr, ptr %v"));
            let none = fb.tmp();
            fb.line(format!("{none} = icmp eq ptr {word}, null"));
            fb.line(format!(
                "br i1 {none}, label %{}, label %{}",
                labels[0], labels[1]
            ));
        } else {
            let loaded = fb.tmp();
            fb.line(format!("{loaded} = load {tag}, ptr %v"));
            let cases: Vec<String> = variants
                .iter()
                .zip(&labels)
                .map(|(v, label)| format!("{tag} {}, label %{label}", tag_literal(v.tag)))
                .collect();
            fb.line(format!(
                "switch {tag} {loaded}, label %{done} [ {} ]",
                cases.join(" ")
            ));
        }
        for ((variant, label), name) in variants.iter().zip(&labels).zip(names) {
            fb.start(label);
            self.show_text(fb, &format!("{prefix}{name}"))?;
            if let Some(payload) = variant.payload {
                self.show_text(fb, "(")?;
                let at = fb.at("%v", if niche { 0 } else { payload_offset });
                self.show_value(fb, &at, payload)?;
                self.show_text(fb, ")")?;
            }
            fb.line(format!("br label %{done}"));
        }
        fb.start(&done);
        Ok(())
    }

    /// `_I.entry` for a fallible `main`: on an error it writes `error: ` and the
    /// structural form of the value, then a newline, and returns 1 (05 section 33.1).
    pub(crate) fn emit_fallible_entry(
        &mut self,
        symbol: &str,
        body: &Body,
        error: TypeId,
        from: ModuleId,
    ) -> Result<(), BuildError> {
        let ret = body.sig.ret;
        let int_status = match self.program.decls.types.kind(ret).clone() {
            TyKind::Int(IntTy::U8) => Some(("i8", true)),
            TyKind::Int(IntTy::I32) => Some(("i32", false)),
            _ if ret == self.program.decls.types.void => None,
            _ => return self.ni("main's result (B1: `void`, `u8` or `i32`, fallible or not)"),
        };
        let abi = self.ret_abi(&body.sig)?;
        let Some(result) = abi.result().cloned() else {
            return Err(BuildError::Internal(
                "a fallible main without a result convention".to_string(),
            ));
        };
        let ret_ll = abi.ret_ll();
        let mut fb = Fb::new();
        let slot = fb.tmp();
        let params = if body.sig.params.is_empty() {
            String::new()
        } else if body.sig.params.len() == 1
            && matches!(
                self.program.decls.types.kind(body.sig.params[0].ty),
                TyKind::Ref(..)
            )
        {
            "ptr %env".to_string()
        } else {
            return self.ni("main's parameters (B1: none or `&Env`)");
        };
        let tag = fb.tmp();
        if result.ptr {
            fb.line(format!(
                "{slot} = alloca [{} x i8], align {}",
                result.payload_area,
                result.payload_align.max(8)
            ));
            let args = if params.is_empty() {
                format!("ptr {slot}")
            } else {
                format!("{params}, ptr {slot}")
            };
            fb.line(format!(
                "{tag} = call {ret_ll} {}({args})",
                global_ref(symbol)
            ));
        } else {
            fb.line(format!("{slot} = alloca i64, align 8"));
            let pair = fb.tmp();
            fb.line(format!(
                "{pair} = call {ret_ll} {}({params})",
                global_ref(symbol)
            ));
            fb.line(format!("{tag} = extractvalue {ret_ll} {pair}, 0"));
            let payload = fb.tmp();
            fb.line(format!("{payload} = extractvalue {ret_ll} {pair}, 1"));
            fb.line(format!("store i64 {payload}, ptr {slot}"));
        }
        let is_ok = fb.tmp();
        fb.line(format!("{is_ok} = icmp eq {} {tag}, 0", result.tag_ll));
        fb.line(format!("br i1 {is_ok}, label %ok, label %failed"));
        fb.start("ok");
        match int_status {
            Some((ll, true)) => {
                let byte = fb.tmp();
                fb.line(format!("{byte} = load {ll}, ptr {slot}"));
                let status = fb.tmp();
                fb.line(format!("{status} = zext {ll} {byte} to i32"));
                fb.line(format!("ret i32 {status}"));
            }
            Some((ll, false)) => {
                let status = fb.tmp();
                fb.line(format!("{status} = load {ll}, ptr {slot}"));
                fb.line(format!("ret i32 {status}"));
            }
            None => fb.line("ret i32 0"),
        }
        fb.start("failed");
        self.show_text(&mut fb, "error: ")?;
        self.show_value(&mut fb, &slot, error)?;
        self.show_text(&mut fb, "\n")?;
        fb.line("ret i32 1");
        let mut out = String::new();
        out.push_str("define internal i32 @_I.entry(ptr %env) nounwind #0 {\n");
        out.push_str("entry:\n");
        for line in &fb.lines {
            out.push_str(line);
            out.push('\n');
        }
        out.push_str("}\n");
        self.functions.push(out);
        self.generate_printers(from)
    }
}
