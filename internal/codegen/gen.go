// Options control code generation.
type Options struct {
	Safe  bool   // bounds checks and division-by-zero checks (default on)
	Tests bool   // generate a test-runner main instead of using the user's main
	Src   []byte // source text, used to quote failed assertions
}

const (
	gprBase  = 19 // pool: x19..x28 (callee-saved: survive calls)
	gprCount = 10
	fprBase  = 16 // pool: v16..v31 (caller-saved: spilled around calls)
	fprCount = 16
	saveArea = 144 // bytes below x29 reserved for x19..x28 and d8..d15
)

// reg is an allocated pool register, or (abs != 0) a borrowed read-only
// view of a promoted variable's register.
type reg struct {
	n   int
	fp  bool
	abs int
}

type loopLabels struct {
	brk, cont string
	depth     int // len(defers) at loop entry; break/continue run deeper defers
}

type gen struct {
	t    Target
	info *sema.Info
	opt  Options
	dl   *diag.List

	mod     strings.Builder
	strs    []string
	strIdx  map[string]int
	labelN  int
	externs map[string]bool

	// per function
	w        *strings.Builder
	body     *sema.Body
	slots    map[*sema.Var]int64
	byRef    map[*sema.Var]bool
	frame    int64
	outArgs  int64
	gpr      [gprCount]bool
	gprTouch [gprCount]bool
	fpr      [fprCount]bool
	fprSpill [fprCount]int64
	loops    []loopLabels
	defers   [][]*syntax.Block // per open block, in declaration order
	errFor   *syntax.CallExpr  // fallible call whose error code (x1) goes to errReg
	errReg   reg
	bodies   map[*sema.Func]*sema.Body // for inline expansion
	inl      *inlineCtx                // non-nil while expanding an inline fn body
	errNext  bool                      // the next emitted call is errFor (its arguments are already evaluated)
	retLabel string
	retSlot  int64 // slot holding x8 for aggregate returns
	stubs    strings.Builder
	failed   bool

	promoted  map[*sema.Var]preg
	tempG     int  // number of pool registers available for temporaries
	final     bool // last allocation attempt: report exhaustion as an error
	exhausted bool
	fprTouch  [8]bool // d8..d15
	srcLines  []string
}

// Generate produces assembly for the whole program.
func Generate(t Target, info *sema.Info, opt Options, dl *diag.List) (string, bool) {
	g := &gen{t: t, info: info, opt: opt, dl: dl, strIdx: map[string]int{}, externs: map[string]bool{}}
	g.mod.WriteString("// Generated by the Ingot compiler. Target: " + t.Name + "\n")
	if !t.Darwin {
		g.mod.WriteString("\t.arch armv8.4-a\n")
	}
	g.mod.WriteString("\t" + t.TextSection() + "\n")
	for _, f := range info.Funcs {
		if f.Extern {
			g.externs[f.Name] = true
		}
	}
	g.bodies = map[*sema.Func]*sema.Body{}
	for _, b := range info.Bodies {
		if b.Func != nil {
			g.bodies[b.Func] = b
		}
	}
	bodies := info.Bodies
	if opt.Tests {
		bodies = append(append([]*sema.Body(nil), info.Bodies...), info.Tests...)
	}
	for _, b := range bodies {
		if opt.Tests && b.Func != nil && b.Func.Name == "main" {
			continue
		}
		g.function(b)
	}
	if opt.Tests {
		g.testMain()
	}
	g.runtime()
	g.data()
	if t.Darwin {
		g.mod.WriteString("\t.subsections_via_symbols\n")
	}
	return g.mod.String(), !g.failed
}

func (g *gen) emit(format string, args ...any) {
	g.w.WriteString("\t")
	fmt.Fprintf(g.w, format, args...)
	g.w.WriteString("\n")
}

func (g *gen) label(l string) { g.w.WriteString(l + ":\n") }

func (g *gen) newLabel(kind string) string {
	g.labelN++
	return g.t.Local(fmt.Sprintf("%s%d", kind, g.labelN))
}

func (g *gen) errorf(sp diag.Span, format string, args ...any) {
	g.failed = true
	g.dl.Errorf("E0900", sp, format, args...)
}

// ---- registers ----

func (g *gen) allocG(sp diag.Span) reg {
	for i := 0; i < g.tempG; i++ {
		if !g.gpr[i] {
			g.gpr[i], g.gprTouch[i] = true, true
			return reg{n: i}
		}
	}
	if !g.final {
		g.exhausted = true
		return reg{n: 0}
	}
	g.errorf(sp, "expression is too deeply nested for the register allocator (more than %d live integer temporaries); split it into 'let' bindings", gprCount)
	return reg{n: 0}
}

func (g *gen) allocF(sp diag.Span) reg {
	for i := 0; i < fprCount; i++ {
		if !g.fpr[i] {
			g.fpr[i] = true
			return reg{n: i, fp: true}
		}
	}
	g.errorf(sp, "expression is too deeply nested for the register allocator (more than %d live vector temporaries); split it into 'let' bindings", fprCount)
	return reg{n: 0, fp: true}
}

func (g *gen) alloc(t *sema.Type, sp diag.Span) reg {
	if t.IsFPR() {
		return g.allocF(sp)
	}
	return g.allocG(sp)
}

func (g *gen) free(r reg) {
	if r.abs != 0 {
		return
	}
	if r.fp {
		g.fpr[r.n] = false
	} else {
		g.gpr[r.n] = false
	}
}

func num(r reg) int {
	switch {
	case r.abs != 0:
		return r.abs
	case r.fp:
		return fprBase + r.n
	}
	return gprBase + r.n
}

func x(r reg) string { return fmt.Sprintf("x%d", num(r)) }
func w(r reg) string { return fmt.Sprintf("w%d", num(r)) }
func v(r reg) string { return fmt.Sprintf("v%d", num(r)) }

// rn names a register for a scalar type.
func rn(r reg, t *sema.Type) string {
	if r.fp {
		switch {
		case t.Kind == sema.Vec:
			return fmt.Sprintf("q%d", num(r))
		case t.Size == 4:
			return fmt.Sprintf("s%d", num(r))
		}
		return fmt.Sprintf("d%d", num(r))
	}
	return x(r)
}

func arr(t *sema.Type) string {
	switch t.Elem.Size {
	case 1:
		return "16b"
	case 2:
		return "8h"
	case 4:
		return "4s"
	}
	return "2d"
}

func laneSuffix(t *sema.Type) string {
	switch t.Elem.Size {
	case 1:
		return "b"
	case 2:
		return "h"
	case 4:
		return "s"
	}
	return "d"
}

// ---- frame ----

func (g *gen) slot(size, align int64) int64 {
	if align < 1 {
		align = 1
	}
	off := (g.frame + size + align - 1) / align * align
	g.frame = off
	return off
}

// mem returns an addressing operand for x29-off; may emit into x16.
func (g *gen) mem(off int64) string {
	if off <= 256 {
		return fmt.Sprintf("[x29, #-%d]", off)
	}
	g.subImm("x16", "x29", off)
	return "[x16]"
}

func (g *gen) subImm(dst, src string, off int64) {
	if off < 4096 {
		g.emit("sub %s, %s, #%d", dst, src, off)
		return
	}
	g.movImm("x17", uint64(off))
	g.emit("sub %s, %s, x17", dst, src)
}

func (g *gen) addImm(dst, src string, off int64) {
	switch {
	case off == 0:
		if dst != src {
			g.emit("mov %s, %s", dst, src)
		}
	case off < 4096:
		g.emit("add %s, %s, #%d", dst, src, off)
	default:
		g.movImm("x17", uint64(off))
		g.emit("add %s, %s, x17", dst, src)
	}
}

// movImm materializes a 64-bit constant.
func (g *gen) movImm(dst string, u uint64) {
	s := int64(u)
	if u < 65536 || (s < 0 && s >= -65536) {
		g.emit("mov %s, #%d", dst, s)
		return
	}
	first := true
	for sh := 0; sh < 64; sh += 16 {
		part := (u >> sh) & 0xffff
		if part == 0 {
			continue
		}
		if first {
			g.emit("movz %s, #%d, lsl #%d", dst, part, sh)
			first = false
		} else {
			g.emit("movk %s, #%d, lsl #%d", dst, part, sh)
		}
	}
}

// ---- loads and stores ----

func (g *gen) load(r reg, addr string, t *sema.Type) {
	switch {
	case r.fp:
		g.emit("ldr %s, %s", rn(r, t), addr)
	case t.Kind == sema.Bool || (t.Kind == sema.Int && t.Size == 1 && !t.Signed):
		g.emit("ldrb %s, %s", w(r), addr)
	case t.Kind == sema.Int && t.Size == 1:
		g.emit("ldrsb %s, %s", x(r), addr)
	case t.Kind == sema.Int && t.Size == 2 && !t.Signed:
		g.emit("ldrh %s, %s", w(r), addr)
	case t.Kind == sema.Int && t.Size == 2:
		g.emit("ldrsh %s, %s", x(r), addr)
	case t.Kind == sema.Int && t.Size == 4 && !t.Signed:
		g.emit("ldr %s, %s", w(r), addr)
	case t.Kind == sema.Int && t.Size == 4:
		g.emit("ldrsw %s, %s", x(r), addr)
	default:
		g.emit("ldr %s, %s", x(r), addr)
	}
}

func (g *gen) store(r reg, addr string, t *sema.Type) {
	switch {
	case r.fp:
		g.emit("str %s, %s", rn(r, t), addr)
	case t.Size == 1:
		g.emit("strb %s, %s", w(r), addr)
	case t.Size == 2:
		g.emit("strh %s, %s", w(r), addr)
	case t.Size == 4:
		g.emit("str %s, %s", w(r), addr)
	default:
		g.emit("str %s, %s", x(r), addr)
	}
}

// normalize re-establishes the invariant that narrow integers are held
// sign- or zero-extended to 64 bits.
func (g *gen) normalize(r reg, t *sema.Type) {
	if t.Kind == sema.Bool {
		return
	}
	if t.Kind != sema.Int || t.Size == 8 {
		return
	}
	switch {
	case t.Signed && t.Size == 1:
		g.emit("sxtb %s, %s", x(r), w(r))
	case t.Signed && t.Size == 2:
		g.emit("sxth %s, %s", x(r), w(r))
	case t.Signed && t.Size == 4:
		g.emit("sxtw %s, %s", x(r), w(r))
	case t.Size == 1:
		g.emit("and %s, %s, #0xff", x(r), x(r))
	case t.Size == 2:
		g.emit("and %s, %s, #0xffff", x(r), x(r))
	case t.Size == 4:
		g.emit("mov %s, %s", w(r), w(r))
	}
}

// normalizeX extends a narrow integer held in register xN.
func (g *gen) normalizeX(n int, t *sema.Type) {
	if t.Kind != sema.Int || t.Size == 8 {
		return
	}
	xs, ws := fmt.Sprintf("x%d", n), fmt.Sprintf("w%d", n)
	switch {
	case t.Signed && t.Size == 1:
		g.emit("sxtb %s, %s", xs, ws)
	case t.Signed && t.Size == 2:
		g.emit("sxth %s, %s", xs, ws)
	case t.Signed:
		g.emit("sxtw %s, %s", xs, ws)
	case t.Size == 1:
		g.emit("and %s, %s, #0xff", xs, xs)
	case t.Size == 2:
		g.emit("and %s, %s, #0xffff", xs, xs)
	default:
		g.emit("mov %s, %s", ws, ws)
	}
}

// copyMem copies size bytes from src to dst (both GPR names). Clobbers x9-x13.
func (g *gen) copyMem(dst, src string, size int64) {
	if size > 128 {
		g.emit("mov x11, %s", src)
		g.emit("mov x12, %s", dst)
		g.movImm("x13", uint64(size/16))
		l := g.newLabel("copy")
		g.label(l)
		g.emit("ldp x9, x10, [x11], #16")
		g.emit("stp x9, x10, [x12], #16")
		g.emit("subs x13, x13, #1")
		g.emit("b.ne %s", l)
		src, dst = "x11", "x12"
		size %= 16
	}
	var o int64
	for ; size-o >= 16; o += 16 {
		g.emit("ldp x9, x10, [%s, #%d]", src, o)
		g.emit("stp x9, x10, [%s, #%d]", dst, o)
	}
	for _, step := range []struct {
		n      int64
		ld, st string
		r      string
	}{{8, "ldr", "str", "x9"}, {4, "ldr", "str", "w9"}, {2, "ldrh", "strh", "w9"}, {1, "ldrb", "strb", "w9"}} {
		for ; size-o >= step.n; o += step.n {
			g.emit("%s %s, [%s, #%d]", step.ld, step.r, src, o)
			g.emit("%s %s, [%s, #%d]", step.st, step.r, dst, o)
		}
	}
}

// zeroMem zeroes size bytes at dst. Clobbers x12, x13.
func (g *gen) zeroMem(dst string, size int64) {
	if size > 128 {
		g.emit("mov x12, %s", dst)
		g.movImm("x13", uint64(size/16))
		l := g.newLabel("zero")
		g.label(l)
		g.emit("stp xzr, xzr, [x12], #16")
		g.emit("subs x13, x13, #1")
		g.emit("b.ne %s", l)
		dst = "x12"
		size %= 16
	}
	var o int64
	for ; size-o >= 16; o += 16 {
		g.emit("stp xzr, xzr, [%s, #%d]", dst, o)
	}
	for _, step := range []struct {
		n  int64
		st string
		r  string
	}{{8, "str", "xzr"}, {4, "str", "wzr"}, {2, "strh", "wzr"}, {1, "strb", "wzr"}} {
		for ; size-o >= step.n; o += step.n {
			g.emit("%s %s, [%s, #%d]", step.st, step.r, dst, o)
		}
	}
}

// ---- strings and data ----

func (g *gen) strLabel(s string) string {
	i, ok := g.strIdx[s]
	if !ok {
		i = len(g.strs)
		g.strs = append(g.strs, s)
		g.strIdx[s] = i
	}
	if g.t.Darwin {
		return fmt.Sprintf("l_.str.%d", i)
	}
	return fmt.Sprintf(".Lstr.%d", i)
}

func (g *gen) addrOfSym(dst, sym string) {
	g.emit("adrp %s, %s", dst, g.t.Page(sym))
	g.emit("add %s, %s, %s", dst, dst, g.t.PageOff(sym))
}

func (g *gen) data() {
	if len(g.strs) > 0 {
		g.mod.WriteString("\t" + g.t.CStringSection() + "\n")
		for i, s := range g.strs {
			l := fmt.Sprintf(".Lstr.%d", i)
			if g.t.Darwin {
				l = fmt.Sprintf("l_.str.%d", i)
			}
			fmt.Fprintf(&g.mod, "%s:\n\t.asciz %s\n", l, asmString(s))
		}
	}
	var zero, init []*sema.Var
	for _, gv := range g.info.Globals {
		if gv.Const {
			continue
		}
		if _, ok := g.info.Consts[gv.Decl.(*syntax.GlobalDecl).Value]; ok {
			init = append(init, gv)
		} else {
			zero = append(zero, gv)
		}
	}
	if len(init) > 0 {
		g.mod.WriteString("\t" + g.t.DataSection() + "\n")
		for _, gv := range init {
			k := g.info.Consts[gv.Decl.(*syntax.GlobalDecl).Value]
			fmt.Fprintf(&g.mod, "\t.p2align %d\n%s:\n", log2(gv.Type.Align), g.t.Sym(gv.Name))
			bits := uint64(k.I)
			if gv.Type.Kind == sema.Float {
				if gv.Type.Size == 4 {
					bits = uint64(math.Float32bits(float32(k.F)))
				} else {
					bits = math.Float64bits(k.F)
				}
			}
			dir := map[int64]string{1: ".byte", 2: ".short", 4: ".long", 8: ".quad"}[gv.Type.Size]
			fmt.Fprintf(&g.mod, "\t%s %d\n", dir, bits&mask(gv.Type.Size))
		}
	}
	for _, gv := range zero {
		size := max(gv.Type.Size, 1)
		if g.t.Darwin {
			fmt.Fprintf(&g.mod, "\t.zerofill __DATA,__bss,%s,%d,%d\n", g.t.Sym(gv.Name), size, log2(gv.Type.Align))
		} else {
			fmt.Fprintf(&g.mod, "\t.bss\n\t.p2align %d\n%s:\n\t.zero %d\n", log2(gv.Type.Align), gv.Name, size)
		}
	}
}

func mask(size int64) uint64 {
	if size >= 8 {
		return ^uint64(0)
	}
	return (uint64(1) << (8 * size)) - 1
}

func log2(n int64) int {
	k := 0
	for int64(1)<<k < n {
		k++
	}
	return k
}

func asmString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c >= 32 && c < 127:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// ---- runtime ----

func (g *gen) runtime() {
	s := g.t.Sym
	fmt.Fprintf(&g.mod, `	.p2align 2
%[1]s:
	stp x29, x30, [sp, #-16]!
	mov x29, sp
	mov x2, x1
	mov x1, x0
	mov x0, #2
	bl %[2]s
	mov x0, #101
	bl %[3]s
	brk #1
`, s("ingot_rt_panic"), s("write"), s("exit"))
}

// panicStub emits an out-of-line call to the panic routine and returns its label.
func (g *gen) panicStub(sp diag.Span, msg string) string {
	l := g.newLabel("panic")
	text := fmt.Sprintf("%s:%d:%d: %s\n", sp.File, sp.Start.Line, sp.Start.Col, msg)
	lbl := g.strLabel(text)
	fmt.Fprintf(&g.stubs, "%s:\n\tadrp x0, %s\n\tadd x0, x0, %s\n\tmov x1, #%d\n\tbl %s\n", l, g.t.Page(lbl), g.t.PageOff(lbl), len(text), g.t.Sym("ingot_rt_panic"))
	return l
}

func (g *gen) srcText(sp diag.Span) string {
	if g.opt.Src == nil || sp.Start.Line != sp.End.Line {
		return ""
	}
	if g.srcLines == nil {
		g.srcLines = strings.Split(string(g.opt.Src), "\n")
	}
	lines := g.srcLines
	if sp.Start.Line-1 >= len(lines) {
		return ""
	}
	ln := lines[sp.Start.Line-1]
	if sp.End.Col-1 > len(ln) || sp.Start.Col < 1 {
		return ""
	}
	return ln[sp.Start.Col-1 : sp.End.Col-1]
}

// ---- functions ----

// function generates one body, retrying with fewer promoted locals if the
// remaining temporaries are not enough for its deepest expression.
func (g *gen) function(b *sema.Body) {
	u := g.analyze(b)
	for maxG := 6; maxG >= 0; maxG-- {
		if g.functionTry(b, u, maxG, maxG == 0) {
			return
		}
	}
}

func (g *gen) functionTry(b *sema.Body, u useInfo, maxG int, final bool) bool {
	var buf strings.Builder
	g.final, g.exhausted = final, false
	g.promoted = g.choosePromotions(b, u, maxG, 8)
	g.tempG = gprCount
	g.fprTouch = [8]bool{}
	for _, p := range g.promoted {
		if !p.fp {
			g.tempG--
		}
	}
	g.w = &buf
	g.body = b
	g.slots = map[*sema.Var]int64{}
	g.byRef = map[*sema.Var]bool{}
	g.frame = saveArea
	g.outArgs = 0
	g.gpr, g.gprTouch, g.fpr = [gprCount]bool{}, [gprCount]bool{}, [fprCount]bool{}
	for i := range g.fprSpill {
		g.fprSpill[i] = 0
	}
	g.stubs.Reset()
	g.retLabel = g.newLabel("ret")
	for _, p := range g.promoted {
		if p.fp {
			g.fprTouch[p.n-8] = true
		} else {
			g.gprTouch[p.n-gprBase] = true
		}
	}
	for _, lv := range g.frameLocals(b) {
		t := lv.Type
		if _, ok := g.promoted[lv]; ok {
			continue
		}
		if contains(b.Params, lv) && t.IsAggregate() {
			g.byRef[lv] = true
			g.slots[lv] = g.slot(8, 8)
			continue
		}
		g.slots[lv] = g.slot(max(t.Size, 1), max(t.Align, 1))
	}
	if b.Ret.IsAggregate() {
		g.retSlot = g.slot(8, 8)
		g.emit("str x8, %s", g.mem(g.retSlot))
	}
	// incoming parameters
	ng, nf := 0, 0
	var stackOff int64
	for _, p := range b.Params {
		t := p.Type
		fp := t.IsFPR()
		isReg := (fp && nf < 8) || (!fp && ng < 8)
		r := reg{n: 0, fp: fp}
		_ = r
		if pr, ok := g.promoted[p]; ok && isReg {
			if fp {
				if t.Kind == sema.Vec {
					g.emit("mov v%d.16b, v%d.16b", pr.n, nf)
				} else {
					g.emit("fmov %s, %s%d", pname(pr, t), pname(pr, t)[:1], nf)
				}
				nf++
			} else {
				g.emit("mov x%d, x%d", pr.n, ng)
				g.normalizeX(pr.n, t) // AAPCS64 leaves the callee to extend narrow args
				ng++
			}
			continue
		}
		if isReg {
			if fp {
				name := fmt.Sprintf("d%d", nf)
				if t.Kind == sema.Vec {
					name = fmt.Sprintf("q%d", nf)
				} else if t.Size == 4 {
					name = fmt.Sprintf("s%d", nf)
				}
				g.emit("str %s, %s", name, g.mem(g.slots[p]))
				nf++
			} else {
				sz := t.Size
				if g.byRef[p] {
					sz = 8
				}
				g.storeArgReg(ng, sz, g.slots[p])
				ng++
			}
			continue
		}
		// stack-passed argument at [x29 + 16 + off]
		size := t.Size
		if g.byRef[p] {
			size = 8
		}
		off := stackSlot(&stackOff, size, g.t.Darwin)
		src := fmt.Sprintf("[x29, #%d]", 16+off)
		if pr, ok := g.promoted[p]; ok {
			tmp := g.alloc(t, b.Block.Sp)
			g.load(tmp, src, t)
			g.writePromoted(pr, t, tmp)
			g.free(tmp)
			continue
		}
		if fp {
			name := map[int64]string{4: "s0", 8: "d0", 16: "q0"}[size]
			g.emit("ldr %s, %s", name, src)
			g.emit("str %s, %s", name, g.mem(g.slots[p]))
		} else {
			g.emit("ldr x9, %s", src)
			g.storeX9(size, g.slots[p])
		}
	}
	g.block(b.Block)
	if g.exhausted && !final {
		return false
	}
	if b.Ret == sema.TVoid || b.Test != nil {
		// fallthrough return (success for a fallible void function)
		if b.Err != nil {
			g.emit("mov x1, #0")
		}
	} else {
		g.emit("brk #1") // unreachable: checker guarantees a return
	}
	// assemble function
	sym := g.t.Sym(b.Name)
	if b.Func != nil {
		sym = g.funcSym(b.Func)
	}
	var out strings.Builder
	out.WriteString("\n\t.p2align 4\n")
	if b.Func != nil && (b.Func.Pub || b.Name == "main") {
		fmt.Fprintf(&out, "\t.globl %s\n", sym)
	}
	fmt.Fprintf(&out, "%s:\n", sym)
	frame := (g.frame + g.outArgs + 15) / 16 * 16
	out.WriteString("\tstp x29, x30, [sp, #-16]!\n\tmov x29, sp\n")
	if frame > 0 {
		if frame < 4096 {
			fmt.Fprintf(&out, "\tsub sp, sp, #%d\n", frame)
		} else {
			fmt.Fprintf(&out, "\tmov x16, #%d\n\tmovk x16, #%d, lsl #16\n\tsub sp, sp, x16\n", frame&0xffff, frame>>16)
		}
	}
	saves := g.savePairs()
	for _, s := range saves {
		fmt.Fprintf(&out, "\tstp %s, %s, [x29, #-%d]\n", s.a, s.b, s.off)
	}
	out.WriteString(buf.String())
	out.WriteString(g.retLabel + ":\n")
	for _, s := range saves {
		fmt.Fprintf(&out, "\tldp %s, %s, [x29, #-%d]\n", s.a, s.b, s.off)
	}
	out.WriteString("\tmov sp, x29\n\tldp x29, x30, [sp], #16\n\tret\n")
	out.WriteString(g.stubs.String())
	g.mod.WriteString(out.String())
	return true
}

type savePair struct {
	a, b string
	off  int
}

func (g *gen) savePairs() []savePair {
	var ps []savePair
	for i := 0; i < gprCount; i += 2 {
		if g.gprTouch[i] || g.gprTouch[i+1] {
			ps = append(ps, savePair{fmt.Sprintf("x%d", gprBase+i), fmt.Sprintf("x%d", gprBase+i+1), 16 * (i/2 + 1)})
		}
	}
	for i := 0; i < 8; i += 2 {
		if g.fprTouch[i] || g.fprTouch[i+1] {
			ps = append(ps, savePair{fmt.Sprintf("d%d", 8+i), fmt.Sprintf("d%d", 9+i), 80 + 16*(i/2+1)})
		}
	}
	return ps
}

func (g *gen) storeArgReg(n int, size, off int64) {
	switch size {
	case 1:
		g.emit("strb w%d, %s", n, g.mem(off))
	case 2:
		g.emit("strh w%d, %s", n, g.mem(off))
	case 4:
		g.emit("str w%d, %s", n, g.mem(off))
	default:
		g.emit("str x%d, %s", n, g.mem(off))
	}
}

func (g *gen) storeX9(size, off int64) {
	switch size {
	case 1:
		g.emit("strb w9, %s", g.mem(off))
	case 2:
		g.emit("strh w9, %s", g.mem(off))
	case 4:
		g.emit("str w9, %s", g.mem(off))
	default:
		g.emit("str x9, %s", g.mem(off))
	}
}

// stackSlot assigns a stack argument offset. Darwin packs stack arguments
// at their natural alignment; AAPCS64 (Linux) rounds each up to 8 bytes.
func stackSlot(cur *int64, size int64, darwin bool) int64 {
	a := size
	if !darwin && a < 8 {
		a = 8
	}
	off := (*cur + a - 1) / a * a
	if darwin {
		*cur = off + size
	} else {
		*cur = off + max(size, 8)
	}
	return off
}

func contains(vs []*sema.Var, v *sema.Var) bool {
	for _, x := range vs {
		if x == v {
			return true
		}
	}
	return false
}

func (g *gen) testMain() {
	var buf strings.Builder
	g.w = &buf
	g.stubs.Reset()
	write := func(s string) {
		l := g.strLabel(s)
		g.emit("mov x0, #1")
		g.addrOfSym("x1", l)
		g.emit("mov x2, #%d", len(s))
		g.emit("bl %s", g.t.Sym("write"))
	}
	for _, tb := range g.info.Tests {
		write("test " + strconv.Quote(tb.Test.Name) + " ... ")
		g.emit("bl %s", g.t.Sym(tb.Name))
		write("ok\n")
	}
	write(fmt.Sprintf("%d tests passed\n", len(g.info.Tests)))
	fmt.Fprintf(&g.mod, "\n\t.p2align 4\n\t.globl %[1]s\n%[1]s:\n\tstp x29, x30, [sp, #-16]!\n\tmov x29, sp\n%[2]s\tmov w0, #0\n\tldp x29, x30, [sp], #16\n\tret\n", g.t.Sym("main"), buf.String())
}
